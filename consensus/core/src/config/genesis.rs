use crate::{block::Block, header::Header};
use spora_exec::CellTx;
use spora_hashes::{Hash, ZERO_HASH};

/// The constants uniquely representing the genesis block
#[derive(Clone, Debug)]
pub struct GenesisBlock {
    pub hash: Hash,
    pub version: u32,
    pub hash_merkle_root: Hash,
    pub cell_commitment: Hash,
    pub timestamp: u64,
    pub bits: u32,
    pub nonce: u64,
    pub daa_score: u64,
    pub coinbase_payload: &'static [u8],
}

impl GenesisBlock {
    /// Build genesis transactions as CellTx
    ///
    /// NOTE: Genesis contains empty coinbase in Cell model
    /// Cell-based coinbase will be implemented in mining layer
    pub fn build_genesis_transactions(&self) -> Vec<CellTx> {
        // Genesis block has no transactions in Cell model
        // Coinbase rewards are handled differently in GhostDAG mergeset
        vec![]
    }
}

impl From<&GenesisBlock> for Header {
    fn from(genesis: &GenesisBlock) -> Self {
        Header::new_finalized(
            genesis.version,
            Vec::new(),
            genesis.hash_merkle_root,
            ZERO_HASH,
            genesis.cell_commitment,
            ZERO_HASH, // cell_root (genesis has no cells yet)
            ZERO_HASH, // segment_root
            genesis.timestamp,
            genesis.bits,
            genesis.nonce,
            genesis.daa_score,
            0.into(),
            0,
            ZERO_HASH,
        )
    }
}

impl From<&GenesisBlock> for Block {
    fn from(genesis: &GenesisBlock) -> Self {
        Block::new(genesis.into(), genesis.build_genesis_transactions())
    }
}

impl From<(&Header, &'static [u8])> for GenesisBlock {
    fn from((header, payload): (&Header, &'static [u8])) -> Self {
        Self {
            hash: header.hash,
            version: header.version,
            hash_merkle_root: header.hash_merkle_root,
            cell_commitment: header.cell_commitment,
            timestamp: header.timestamp,
            bits: header.bits,
            nonce: header.nonce,
            daa_score: header.daa_score,
            coinbase_payload: payload,
        }
    }
}

