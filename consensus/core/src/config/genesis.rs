#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::bps::TenBps;

    const GENESIS_BLOCKS: &[GenesisBlock] = &[GENESIS, TESTNET_GENESIS, TESTNET11_GENESIS, SIMNET_GENESIS, DEVNET_GENESIS];

    #[test]
    #[ignore = "Genesis hashes need to be regenerated after CellTx version field type changed from u16 to u32"]
    fn test_genesis_hashes() {
        GENESIS_BLOCKS.iter().for_each(|genesis| {
            let block: Block = genesis.into();
            assert!(block.transactions.is_empty());
            assert_hashes_eq(block.header.hash_merkle_root, genesis.hash_merkle_root);
            assert_hashes_eq(block.hash(), genesis.hash);
        });
    }

    #[test]
    fn gen_testnet11_genesis() {
        let bps = TenBps::bps();
        let mut genesis = TESTNET_GENESIS;
        let target = spora_math::Uint256::from_compact_target_bits(genesis.bits);
        let scaled_target = target * bps / 100;
        let scaled_bits = scaled_target.compact_target_bits();
        genesis.bits = scaled_bits;
        if genesis.bits != TESTNET11_GENESIS.bits {
            panic!("Testnet 11: new bits: {}\nnew hash: {:#04x?}", scaled_bits, Block::from(&genesis).hash().as_bytes());
        }
    }

    #[test]
    fn calculate_new_genesis_hashes() {
        // Calculate new hashes for each genesis block
        for (i, genesis) in GENESIS_BLOCKS.iter().enumerate() {
            let block: Block = (genesis).into();
            let hash = block.hash();
            let merkle_root = block.header.hash_merkle_root;
            let cell_commitment = block.header.cell_commitment;

            println!("Genesis Block {}:", i);
            println!("Hash: {:#04x?}", hash.as_bytes());
            println!("Merkle Root: {:#04x?}", merkle_root.as_bytes());
            println!("Cell Commitment: {:#04x?}", cell_commitment.as_bytes());
            println!();
        }
    }

    fn assert_hashes_eq(got: Hash, expected: Hash) {
        if got != expected {
            // Special hex print to ease changing the genesis hash according to the print if needed
            panic!("Got hash {:#04x?} while expecting {:#04x?}", got.as_bytes(), expected.as_bytes());
        }
    }
}
