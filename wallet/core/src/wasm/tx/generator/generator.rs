/// Generator is a type capable of generating transactions based on a supplied
/// set of cell entries or a cell entry producer (such as {@link CellContext}). The Generator
/// accumulates cell entries until it can generate a transaction that meets the
/// requested amount or until the total mass of created inputs exceeds the allowed
/// transaction mass, at which point it will produce a compound transaction by forwarding
/// all selected cell entries to the supplied change address and prepare to start generating
/// a new transaction.  Such sequence of daisy-chained transactions is known as a "batch".
/// Each compound transaction results in a new cell, which is immediately reused in the
/// subsequent transaction.
///
/// The Generator constructor accepts a single {@link IGeneratorSettingsObject} object.
///
/// ```javascript
///
/// let generator = new Generator({
///     entries : [...],
///     changeAddress : "spora:...",
///     outputs : [
///         { amount : sporaToSau(10.0), address: "spora:..."},
///         { amount : sporaToSau(20.0), address: "spora:..."},
///         ...
///     ],
///     priorityFee : 1000n,
/// });
///
/// let pendingTransaction;
/// while(pendingTransaction = await generator.next()) {
///     await pendingTransaction.sign(privateKeys);
///     await pendingTransaction.submit(rpc);
/// }
///
/// let summary = generator.summary();
/// console.log(summary);
///
/// ```
/// @see
///     {@link IGeneratorSettingsObject},
///     {@link PendingTransaction},
///     {@link CellContext},
///     {@link createTransactions},
///     {@link estimateTransactions},
/// @category Wallet SDK
#[wasm_bindgen]
pub struct Generator {
    inner: Arc<native::Generator>,
}

#[wasm_bindgen]
impl Generator {
    #[wasm_bindgen(constructor)]
    pub fn ctor(args: IGeneratorSettingsObject) -> Result<Generator> {
        let settings = GeneratorSettings::try_from(args)?;

        let GeneratorSettings {
            network_id,
            source,
            priority_cell_entries,
            multiplexer,
            final_transaction_destination,
            change_address,
            fee_rate,
            final_priority_fee,
            minimum_signatures,
            payload,
            header_deps,
            cell_deps,
            ckb_type_id_output_indexes,
            final_cellscript_compiled_scheduler_witness,
            cellscript_typed_cell_scheduler_plan,
            cellscript_typed_cell_outputs,
            cellscript_typed_cell_resolved_cells,
        } = settings;

        let mut settings = match source {
            GeneratorSource::CellEntries(cell_entries) => {
                let change_address = change_address
                    .ok_or_else(|| Error::custom("changeAddress is required for Generator constructor with cell entries"))?;

                let network_id =
                    network_id.ok_or_else(|| Error::custom("networkId is required for Generator constructor with cell entries"))?;

                native::GeneratorSettings::try_new_with_iterator(
                    network_id,
                    Box::new(cell_entries.into_iter()),
                    priority_cell_entries,
                    change_address,
                    minimum_signatures,
                    final_transaction_destination,
                    fee_rate,
                    final_priority_fee,
                    payload,
                    multiplexer,
                )?
            }
            GeneratorSource::CellContext(cell_context) => {
                let change_address = change_address
                    .ok_or_else(|| Error::custom("changeAddress is required for Generator constructor with cell entries"))?;

                native::GeneratorSettings::try_new_with_context(
                    cell_context.into(),
                    priority_cell_entries,
                    change_address,
                    minimum_signatures,
                    final_transaction_destination,
                    final_priority_fee,
                    payload,
                    multiplexer,
                )?
            } // GeneratorSource::Account(account) => {
              //     let account: Arc<dyn crate::account::Account> = account.into();
              //     native::GeneratorSettings::try_new_with_account(account, final_transaction_destination, final_priority_fee, None)?
              // }
        }
        .with_header_deps(header_deps)
        .with_cell_deps(cell_deps)
        .with_ckb_type_id_output_indexes(ckb_type_id_output_indexes);
        settings = settings
            .with_cellscript_typed_cell_outputs(cellscript_typed_cell_outputs)
            .with_cellscript_typed_cell_resolved_cells(cellscript_typed_cell_resolved_cells);
        if let Some(plan) = cellscript_typed_cell_scheduler_plan {
            settings = settings.with_cellscript_typed_cell_scheduler_plan(plan)?;
        }
        if let Some(witness) = final_cellscript_compiled_scheduler_witness {
            settings = settings.try_with_cellscript_compiled_scheduler_witness(witness)?;
        }

        let abortable = Abortable::default();
        let generator = native::Generator::try_new(settings, None, Some(&abortable))?;

        Ok(Self { inner: Arc::new(generator) })
    }

    /// Generate next transaction
    pub async fn next(&self) -> Result<JsValue> {
        if let Some(transaction) = self.inner.generate_transaction().transpose() {
            let transaction = PendingTransaction::from(transaction?);
            Ok(transaction.into())
        } else {
            Ok(JsValue::NULL)
        }
    }

    pub async fn estimate(&self) -> Result<GeneratorSummary> {
        let mut stream = self.inner.stream();
        while stream.try_next().await?.is_some() {}
        Ok(self.summary())
    }

    pub fn summary(&self) -> GeneratorSummary {
        self.inner.summary().into()
    }
}

impl Generator {
    pub fn iter(&self) -> impl Iterator<Item = Result<native::PendingTransaction>> {
        self.inner.iter()
    }

    pub fn stream(&self) -> impl Stream<Item = Result<native::PendingTransaction>> {
        self.inner.stream()
    }
}

